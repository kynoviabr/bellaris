const seen = new Set<string>();
export const COUNTRY_OPTIONS = COUNTRY_DIAL_CODES.filter(c => (seen.has(c.code) ? false : (seen.add(c.code), true)));

export function countryNameFor(code: string): string {
  return COUNTRY_OPTIONS.find(c => c.code === code)?.name ?? "";
}

/** Acha o código do país no começo dos dígitos (o mais longo que bater). Ex.: "351912..." -> "351". */
export function detectDialCode(digits: string): string | null {
  for (let len = 3; len >= 1; len--) {
    const prefix = digits.slice(0, len);
    if (prefix.length === len && COUNTRY_OPTIONS.some(c => c.code === prefix)) return prefix;
  }
  return null;
}
